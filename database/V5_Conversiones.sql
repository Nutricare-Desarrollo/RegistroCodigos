    FechaCreacion   TIMESTAMP(0) NOT NULL DEFAULT (now() at time zone 'utc'),
    CONSTRAINT FK_Conversion_Producto FOREIGN KEY (ProductoId) REFERENCES cat.OP_Producto(Id),

   Idempotente: seguro de re-ejecutar.
   ----------------------------------------------------------------------------
   Tabla dbo.Conversion: una conversion Caja->Unid por producto del catalogo
   cat.OP_Producto.  Cajas = Numerator (Dynamics),  UnidadesPorCaja = Factor.
   Solo se cargan los productos que existen en el catalogo (match por el codigo,
   el texto antes del separador en OP_Producto.Nombre).
   ============================================================================ */

